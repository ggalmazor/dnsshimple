// trustyart turns a small PNG of Trusty (DNSimple's mascot) into Go pixel
// data for the TUI. It deliberately emits colors, not ANSI codes: the TUI
// renders cells through each session's lipgloss renderer, so capable
// terminals get truecolor and colorless ones degrade instead of seeing
// escape garbage.
//
// Usage: go run ./tools/trustyart <input.png> > adapters/sshui/art.go
package main

import (
	"fmt"
	"image"
	_ "image/png"
	"os"
)

func main() {
	if len(os.Args) < 2 || len(os.Args) > 3 {
		fmt.Fprintln(os.Stderr, "usage: trustyart <input.png> [varName]")
		os.Exit(1)
	}
	varName := "trustyPixels"
	if len(os.Args) == 3 {
		varName = os.Args[2]
	}
	source, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer func() { _ = source.Close() }()
	decoded, _, err := image.Decode(source)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	bounds := decoded.Bounds()
	fmt.Println("// Code generated by tools/trustyart; DO NOT EDIT.")
	fmt.Println("package sshui")
	fmt.Println()
	fmt.Printf("// %s holds the image as [row][column]{upper, lower} hex colors;\n", varName)
	fmt.Println(`// "" means transparent. Rendered as half-blocks per session.`)
	fmt.Printf("var %s = [][][2]string{\n", varName)
	for y := bounds.Min.Y; y < bounds.Max.Y; y += 2 {
		fmt.Print("\t{")
		for x := bounds.Min.X; x < bounds.Max.X; x++ {
			fmt.Printf("{%q, %q}, ", hexAt(decoded, x, y), hexAt(decoded, x, y+1))
		}
		fmt.Println("},")
	}
	fmt.Println("}")
}

func hexAt(decoded image.Image, x, y int) string {
	if y >= decoded.Bounds().Max.Y {
		return ""
	}
	red, green, blue, alpha := decoded.At(x, y).RGBA()
	if alpha < 0x8000 {
		return ""
	}
	return fmt.Sprintf("#%02x%02x%02x", red>>8, green>>8, blue>>8)
}
